import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync, unlinkSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { gzipSync } from 'node:zlib';
import { createKnowledgeFixture } from '../fixtures/knowledge_fixture.js';

const root = mkdtempSync(join(tmpdir(), 'memory-knowledge-'));
process.env.MEMORY_DIR = join(root, 'memory');
process.env.OPENCODE_CONFIG_DIR = join(root, 'opencode');
process.env.MEMORY_DISABLE_PERSONA_SYNC = '1';
process.env.MEMORY_DISABLE_BACKGROUND_SYNC = '1';
const service = await import('../../mcp-server/services/knowledge_service.js');
const notebook = await import('../../mcp-server/services/notebook_service.js');
const { closeDatabase } = await import('../../mcp-server/db/database.js');
const { getBlobPath } = await import('../../mcp-server/storage/blob_store.js');
const { updateConfig } = await import('../../mcp-server/config/config_manager.js');
const { startDashboard } = await import('../../mcp-server/dashboard/server.js');
const { inspectKnowledgeTool } = await import('../../mcp-server/tools/core/knowledge_inspect_core.js');
const { parseKnowledgeCommand } = await import('../../mcp-server/cli/knowledge_commands.js');
let app;
const nativeFetch = globalThis.fetch;
let networkCalls = 0;
globalThis.fetch = () => { networkCalls++; throw new Error('Network forbidden during knowledge viewing'); };
try {
  const f = await createKnowledgeFixture();
  const { getModelRuntimeStatus } = await import('../../mcp-server/ml/model_manager.js');
  const modelsDir = join(process.env.MEMORY_DIR, 'storage', 'models');
  const modelFilesBefore = readdirSync(modelsDir);
  for (const mode of ['only-local', 'cloud-snapshots']) {
    updateConfig({ mode });
    const targets = await service.listKnowledgeTargets();
    assert.ok(targets.some(target => target.key === f.ragOnly));
    assert.ok((await notebook.notebookOverview()).targets.some(target => target.key === f.ragOnly));
    const empty = await notebook.readNotebook({ key: f.ragOnly });
    assert.equal(empty.records.length, 0); assert.equal(empty.readOnly, true);
    const list = await service.listKnowledge({ scopeKey: f.a });
    assert.equal(list.total, 2); assert.ok(!JSON.stringify(list).includes(f.privateB));
    const combined = await service.listKnowledge({ scopeKey: f.a, includeGlobal: true });
    assert.equal(combined.total, 3);
    assert.equal((await service.listKnowledge({ scopeKey: f.a, sourceType: 'note' })).items[0].docId, f.note);
    assert.equal((await service.listKnowledge({ scopeKey: f.a, sourceType: 'source' })).total, 1);
    assert.equal((await service.listKnowledge({ scopeKey: f.a, query: 'scope' })).total, 1);
    const paged = await service.listKnowledge({ scopeKey: f.a, limit: 1 });
    assert.equal(paged.nextOffset, 1);
    const second = await service.listKnowledge({ scopeKey: f.a, limit: 1, offset: 1 });
    assert.notEqual(paged.items[0].docId, second.items[0].docId);
    const remote = await service.readKnowledge({ scopeKey: f.ragOnly, docId: f.remote });
    assert.match(remote.raw.text, /normalized text/);
    assert.equal(remote.raw.state, 'available');
    assert.equal(remote.index.model, 'UNKNOWN');
    const shared = await service.readKnowledge({ scopeKey: f.a, docId: f.shared, startLine: 3, textLimit: 8 });
    assert.equal(shared.raw.lineStart, 3); assert.equal(shared.raw.text, 'Saved so');
    assert.equal(shared.otherScopeCount, 1); assert.deepEqual(shared.visibleScopes, [f.a]);
    const later = await service.readKnowledge({ scopeKey: f.a, docId: f.shared, rawOffset: shared.raw.nextOffset });
    assert.equal(shared.raw.text + later.raw.text, 'Saved source text.\n\n## Detail\n\nPrivate links remain isolated.');
    const hierarchy = await service.readHierarchy({ scopeKey: f.a, docId: f.shared });
    assert.ok(hierarchy.items.length >= 2);
    const section = hierarchy.items[0];
    const medium = await service.readHierarchy({ scopeKey: f.a, docId: f.shared, level: 'medium', parentId: section.id });
    assert.ok(medium.items.length);
    const micro = await service.readHierarchy({ scopeKey: f.a, docId: f.shared, level: 'micro', parentId: medium.items[0].id });
    assert.ok(micro.items.length);
    const chunk = await service.readChunk({ scopeKey: f.a, docId: f.shared, level: 'micro', chunkId: micro.items[0].id });
    assert.equal(chunk.parentState, 'available'); assert.equal(chunk.vector.model, 'UNKNOWN');
    assert.equal(chunk.coordinates.state, 'UNKNOWN'); assert.ok(!('vector' in chunk && ArrayBuffer.isView(chunk.vector)));
    await assert.rejects(service.readKnowledge({ scopeKey: f.a, docId: f.privateB }), { code: 'NOT_FOUND' });
    await assert.rejects(service.readKnowledge({ scopeKey: f.a, docId: 'Общий источник A/B' }), { code: 'NOT_FOUND' });
    const bMicro = await service.readHierarchy({ scopeKey: f.b, docId: f.privateB, level: 'micro' });
    await assert.rejects(service.readChunk({ scopeKey: f.a, docId: f.shared, level: 'micro', chunkId: bMicro.items[0].id }), { code: 'NOT_FOUND' });
    await assert.rejects(service.readHierarchy({ scopeKey: f.a, docId: f.shared, level: 'medium', parentId: bMicro.items[0].section_id }), { code: 'NOT_FOUND' });
    const links = await service.listKnowledgeLinks({ scopeKey: f.a, docId: f.shared });
    assert.equal(links.total, 2); assert.ok(!JSON.stringify(links).includes('link-b'));
    assert.equal(links.items.find(link => link.linkId === 'link-a').factRef, 'id:same');
    assert.equal(links.items.find(link => link.linkId === 'link-ambiguous').factRef, null);
    assert.ok(links.items.every(link => !link.coordinatesConfirmed && link.status === 'needs_review'));
  }
  updateConfig({ mode: 'only-local' });
  await assert.rejects(service.listKnowledge({ scopeKey: 'git:unregistered' }), { code: 'NOT_FOUND' });
  await assert.rejects(service.listKnowledge({ scopeKey: f.a, limit: 101 }), { code: 'INVALID' });
  await assert.rejects(service.listKnowledge({ scopeKey: f.a, offset: '-1' }), { code: 'INVALID' });
  await assert.rejects(service.listKnowledge({ scopeKey: f.a, includeGlobal: 'false' }), { code: 'INVALID' });
  await assert.rejects(service.inspectKnowledge({ action: 'toString' }), { code: 'INVALID' });
  const db = (await import('../../mcp-server/db/database.js')).getDatabase;
  const currentDb = await db();
  const before = await service.readKnowledge({ scopeKey: f.a, docId: f.shared });
  currentDb.localDb.exec('BEGIN IMMEDIATE');
  await assert.rejects(service.readKnowledge({ scopeKey: f.a, docId: f.shared }), { code: 'BUSY' });
  currentDb.localDb.exec('ROLLBACK');
  await currentDb.prepare('UPDATE documents SET title = ? WHERE id = ?').run('Updated same timestamp', f.shared);
  const after = await service.readKnowledge({ scopeKey: f.a, docId: f.shared });
  assert.notEqual(before.version, after.version);
  const section = (await service.readHierarchy({ scopeKey: f.a, docId: f.shared })).items[0];
  const otherSection = (await service.readHierarchy({ scopeKey: f.b, docId: f.privateB })).items[0];
  const micro = (await service.readHierarchy({ scopeKey: f.a, docId: f.shared, level: 'micro' })).items[0];
  await currentDb.prepare('UPDATE micro_chunks SET section_id = ? WHERE id = ?').run(otherSection.id, micro.id);
  const broken = await service.readChunk({ scopeKey: f.a, docId: f.shared, level: 'micro', chunkId: micro.id });
  assert.equal(broken.parentState, 'missing_or_foreign_section'); assert.equal(broken.section_id, null);
  await currentDb.prepare('UPDATE micro_chunks SET section_id = ? WHERE id = ?').run(section.id, micro.id);
  const row = await currentDb.prepare('SELECT blob_hash FROM documents WHERE id = ?').get(f.remote);
  const blobPath = getBlobPath(row.blob_hash);
  writeFileSync(blobPath, gzipSync('tampered'));
  assert.equal((await service.readKnowledge({ scopeKey: f.ragOnly, docId: f.remote })).raw.state, 'corrupt');
  unlinkSync(blobPath);
  assert.equal((await service.readKnowledge({ scopeKey: f.ragOnly, docId: f.remote })).raw.state, 'missing');
  assert.equal((await service.listKnowledge({ scopeKey: f.ragOnly })).items[0].rawState, 'missing');
  const { saveBlob } = await import('../../mcp-server/storage/blob_store.js');
  const crlf = await saveBlob('first\r\nsecond\r\nthird');
  await currentDb.prepare('UPDATE documents SET blob_hash = ?, checksum = ? WHERE id = ?').run(crlf.hash, crlf.hash, f.remote);
  const numbered = await service.readKnowledge({ scopeKey: f.ragOnly, docId: f.remote, startLine: 2 });
  assert.equal(numbered.raw.text, 'second\nthird'); assert.equal(numbered.raw.lineStart, 2);
  const large = await saveBlob('x'.repeat(17000000));
  await currentDb.prepare('UPDATE documents SET blob_hash = ?, checksum = ? WHERE id = ?').run(large.hash, large.hash, f.remote);
  assert.equal((await service.readKnowledge({ scopeKey: f.ragOnly, docId: f.remote })).raw.state, 'too_large');
  const savedMicro = await currentDb.prepare('SELECT content, vector FROM micro_chunks WHERE id = ?').get(micro.id);
  await currentDb.prepare('UPDATE micro_chunks SET content = ?, vector = ? WHERE id = ?').run('😀' + 'x'.repeat(25000), Buffer.alloc(16), micro.id);
  const unicode = await service.readChunk({ scopeKey: f.a, docId: f.shared, level: 'micro', chunkId: micro.id });
  assert.equal(unicode.vector.dimension, 4); assert.equal(unicode.vector.model, 'UNKNOWN');
  assert.equal(unicode.nextTextOffset, 20000);
  const tail = await service.readChunk({ scopeKey: f.a, docId: f.shared, level: 'micro', chunkId: micro.id, textOffset: unicode.nextTextOffset });
  assert.equal(unicode.text + tail.text, '😀' + 'x'.repeat(25000));
  await currentDb.prepare('UPDATE micro_chunks SET content = ?, vector = ? WHERE id = ?').run(savedMicro.content, savedMicro.vector, micro.id);
  const savedNote = await currentDb.prepare('SELECT title FROM documents WHERE id = ?').get(f.note);
  await currentDb.prepare('UPDATE documents SET title = ? WHERE id = ?').run('T'.repeat(3000), f.note);
  const bounded = await service.readKnowledge({ scopeKey: f.a, docId: f.note });
  assert.equal(bounded.title.length, 2000); assert.equal(bounded.metadataTruncated, true);
  await currentDb.prepare('UPDATE documents SET title = ? WHERE id = ?').run(savedNote.title, f.note);
  assert.equal(networkCalls, 0, 'All service reads and fixtures used zero network calls');
  assert.deepEqual(readdirSync(modelsDir), modelFilesBefore, 'Viewing does not download models');
  assert.equal(getModelRuntimeStatus().embedding.loaded, false);
  assert.equal(getModelRuntimeStatus().reranker.loaded, false);
  assert.equal(JSON.parse((await inspectKnowledgeTool({ action: 'list', scopeKey: f.a })).content[0].text).total, 2);
  assert.equal((await inspectKnowledgeTool({ action: 'read', scopeKey: f.a, docId: f.privateB })).isError, true);
  assert.equal(parseKnowledgeCommand(['read', f.shared, '--scope-key', f.a]).docId, f.shared);
  assert.throws(() => parseKnowledgeCommand(['list', '--scope-key', f.a, '--limit', '1', '--limit', '2']));
  assert.throws(() => parseKnowledgeCommand(['targets', '--include-global']));
  const cli = JSON.parse(execFileSync(process.execPath, ['mcp-server/cli_boot.js', 'knowledge', 'list', '--scope-key', f.a], { encoding: 'utf8', env: process.env }));
  assert.equal(cli.total, 2);
  const { MemoryPlugin } = await import('../../opencode-plugin/main.js');
  const plugin = await MemoryPlugin({ directory: root, worktree: null, client: {} });
  const {readRuntimeStates}=await import('../../mcp-server/ml/model_control.js');
  assert.equal(readRuntimeStates().find(owner=>owner.serverPid===process.pid).controlProtocol,2,'OpenCode V1 registers the shared model control channel');
  assert.ok(plugin.tool.inspect_knowledge);
  assert.equal(JSON.parse(await plugin.tool.inspect_knowledge.execute({ action: 'list', scopeKey: f.a })).total, 2);
  const nativeTools = new Map();
  const nativePlugin = (await import('../../opencode-plugin/main.js')).default;
  await nativePlugin.setup({ location: { directory: root }, session: { hook: async () => {} },
    tool: { transform: async run => run({ add: tool => nativeTools.set(tool.name, tool) }) } });
  assert.ok(nativeTools.has('inspect_knowledge'));
  assert.equal(readRuntimeStates().filter(owner=>owner.serverPid===process.pid).length,1,'OpenCode V2 reuses the same process owner');
  assert.equal(JSON.parse((await nativeTools.get('inspect_knowledge').execute({ action: 'list', scopeKey: f.a })).content).total, 2);
  // Exercise the public MCP schema/stdio path, not just the core function.
  const { Client } = await import('@modelcontextprotocol/sdk/client/index.js');
  const { StdioClientTransport } = await import('@modelcontextprotocol/sdk/client/stdio.js');
  const client = new Client({ name: 'knowledge-read-test', version: '1.0' });
  const transport = new StdioClientTransport({ command: process.execPath, args: ['mcp-server/index.js'], env: process.env, stderr: 'pipe' });
  try {
    await client.connect(transport);
    assert.ok((await client.listTools()).tools.some(tool => tool.name === 'inspect_knowledge'));
    const response = await client.callTool({ name: 'inspect_knowledge', arguments: { action: 'list', scopeKey: f.a, limit: 1 } });
    assert.equal(JSON.parse(response.content[0].text).items.length, 1);
    const denied = await client.callTool({ name: 'inspect_knowledge', arguments: { action: 'read', scopeKey: f.a, docId: f.privateB } });
    assert.equal(denied.isError, true);
    const invalid = await client.callTool({ name: 'inspect_knowledge', arguments: { action: 'list', scopeKey: f.a, limit: 'garbage' } });
    assert.equal(JSON.parse(invalid.content[0].text).code, 'INVALID');
  } finally { await client.close(); }
  globalThis.fetch = nativeFetch;
  app = await startDashboard();
  const headers = { Authorization: `Bearer ${new URL(app.url).hash.slice(1)}` };
  const url = `${app.origin}/api/knowledge?action=read&scopeKey=${encodeURIComponent(f.a)}&docId=${f.note}`;
  assert.equal((await fetch(url)).status, 401);
  assert.equal((await fetch(url, { headers: { ...headers, Origin: 'https://evil.example' } })).status, 403);
  assert.equal((await fetch(url, { headers })).status, 200);
  assert.equal((await fetch(url.replace(f.note, f.privateB), { headers })).status, 404);
  assert.equal((await fetch(url + '&scopeKey=global', { headers })).status, 400);
  assert.equal((await fetch(url + '&includeGlobal=garbage', { headers })).status, 400);
  assert.equal((await fetch(app.origin + '/knowledge.js')).status, 200);
  console.log('Knowledge K1: isolation, offline targets, pagination, hierarchy, legacy links, corrupt blobs, CLI/tool/HTTP PASS');
} finally {
  globalThis.fetch = nativeFetch;
  if (app) await app.close();
  closeDatabase(); rmSync(root, { recursive: true, force: true, maxRetries: 5 });
}
